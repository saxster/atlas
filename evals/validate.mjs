// Deterministic offline validator for evals/ briefs, planted-fault fixtures,
// strict orthographic drafting/export/compact checks, and multi-theme PNG rendering.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import {
  draftSvg,
  draftArrow,
  draftDimension,
  draftHatch,
  draftSupportTicks,
  draftInverseClip,
  draftClearanceMask,
  draftCompactSvg,
} from '../engine/draft_kit.js';
import { lintSvg } from '../cli/svg-lint.mjs';
import { exportSvg } from '../cli/export-svg.mjs';
import { renderSvgToPng } from '../cli/svg-render.mjs';
import { auditFigureDir } from '../cli/check.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const BRIEFS_DIR = path.join(ROOT, 'evals', 'briefs');
const PNG_MAGIC = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);

// 1. Verify all 8 cold-run briefs exist and are non-empty
const briefs = fs.readdirSync(BRIEFS_DIR).filter(f => /^\d{2}-.*\.txt$/.test(f)).sort();
assert.equal(briefs.length, 8, `Expected 8 eval briefs, found ${briefs.length}`);
for (const b of briefs) {
  const txt = fs.readFileSync(path.join(BRIEFS_DIR, b), 'utf8').trim();
  assert.ok(txt.length > 40, `Eval brief ${b} is unexpectedly short`);
}
console.log(`PASS  evals/briefs: ${briefs.length} briefs verified`);

// 2. Verify planted faults in faulty-diagram.svg are all detected by lintSvg --strict-draft
const faultySvg = fs.readFileSync(path.join(ROOT, 'evals', 'attachments', 'faulty-diagram.svg'), 'utf8');
const faultyReport = lintSvg(faultySvg, { strictDraft: true, source: 'faulty-diagram.svg' });
assert.equal(faultyReport.ok, false, 'faulty-diagram.svg must fail strictDraft lint');
const rulesFound = new Set(faultyReport.findings.map(f => f.rule));
const expectedFaultRules = [
  'duplicate-id',
  'dangling-ref',
  'stroked-text',
  'upside-down-text',
  'forbidden-effect',
  'forbidden-skew',
  'forbidden-text-style',
  'forbidden-caps-spacing',
  'font-size-range',
  'stroke-width-drift',
];
for (const rule of expectedFaultRules) {
  assert.ok(rulesFound.has(rule), `Expected faulty-diagram.svg to trigger rule "${rule}", got: ${[...rulesFound].join(', ')}`);
}
console.log(`PASS  evals/faulty-diagram.svg: detected all ${expectedFaultRules.length} planted fault rules`);

// 3. Verify clean draft_kit construction passes strict lint, compact derivation, export-svg, and svg-render --theme both
const hatch = draftHatch({ region: { kind: 'rect', x: 80, y: 110, width: 64, height: 120 }, pattern: 'H1' });
const ticks = draftSupportTicks({ from: [80, 90], to: [80, 250], side: -1 });
const dim = draftDimension({
  axis: 'x',
  witnesses: [[80, 110], [420, 170]],
  position: 64,
  label: { text: '340 mm', anchor: [250, 64], clearance: { x: 220, y: 54, width: 60, height: 20 } },
});
const arr = draftArrow({ from: [240, 220], to: [420, 170] });
const inv = draftInverseClip('clear-front', 'M180 130H300V210H180Z', { vb: [0, 0, 560, 320] });
const clr = draftClearanceMask('grid-clear', '<rect x="180" y="130" width="120" height="80" fill="black"/>', { vb: [0, 0, 560, 320] });

const cleanSvg = draftSvg({
  id: 'eval-cantilever',
  vb: [0, 0, 560, 320],
  title: 'Eval cantilever test',
  desc: 'Pure orthographic fixture generated by evals/validate.mjs.',
  mode: 'geometric-construction',
  defs: `${inv.defs}${clr.defs}`,
  body: [
    `<g data-draft-role="grid" ${clr.maskAttr}><path d="M40 170H520M250 30V290"/></g>`,
    `<path data-draft-role="hidden" ${inv.clipAttr} d="M120 150H360"/>`,
    `<path data-draft-role="hatch" d="${hatch.d}"/>`,
    `<path data-draft-role="guide" d="${ticks.d}"/>`,
    `<line data-draft-role="section" x1="80" y1="90" x2="80" y2="250"/>`,
    `<rect data-draft-fill="highlight" x="80" y="110" width="64" height="120"/>`,
    `<path data-draft-role="primary" d="M144 170H420"/>`,
    `<path data-draft-role="transfer" d="${arr.shaftD}"/>`,
    `<path data-draft-role="primary" d="${arr.headD}"/>`,
    `<g data-draft-role="dimension"><path d="${dim.witnessD}"/><path d="${dim.lineD}"/><path d="${dim.slashD}"/></g>`,
    `<text data-draft-text="label" x="${dim.label.anchor[0]}" y="${dim.label.anchor[1] + 4}" text-anchor="middle" font-size="11">${dim.label.text}</text>`,
  ].join(''),
});

const cleanLint = lintSvg(cleanSvg, { strictDraft: true, source: 'clean-draft.svg' });
assert.equal(cleanLint.ok, true, `Clean draftSvg failed strict lint: ${JSON.stringify(cleanLint.findings)}`);

const compactSvg = draftCompactSvg(cleanSvg, { cropBox: [70, 80, 380, 180] });
const compactLint = lintSvg(compactSvg, { compact: true, source: 'compact-draft.svg' });
assert.equal(compactLint.ok, true, `Compact draft failed lint: ${JSON.stringify(compactLint.findings)}`);
assert.equal(compactLint.summary.warnings, 0, 'Expected zero warnings after stripping text from compact draft');

const expLight = exportSvg(cleanSvg, { theme: 'light', idPrefix: 'v1-' });
const expDark = exportSvg(cleanSvg, { theme: 'dark', idPrefix: 'v2-' });
assert.ok(expLight.svg.includes('#18181a'), 'Light export should resolve ink color');
assert.ok(expDark.svg.includes('#eef3f0'), 'Dark export should resolve dark-mode ink color');
assert.ok(expLight.svg.includes('url(#v1-clear-front)'), 'ID prefixing must rewrite clip-path URL');

const tmpOutDir = fs.mkdtempSync(path.join(os.tmpdir(), 'atlas-eval-render-'));
try {
  const rendered = await renderSvgToPng(cleanSvg, {
    outPath: path.join(tmpOutDir, 'eval-plate.png'),
    theme: 'both',
    scale: 1,
  });
  assert.equal(rendered.files.length, 2, 'Expected light and dark PNG outputs');
  for (const f of rendered.files) {
    const buf = fs.readFileSync(f.file);
    assert.ok(buf.subarray(0, 8).equals(PNG_MAGIC), `Rendered file is not a valid PNG: ${f.file}`);
  }
  console.log(`PASS  evals/draft-pipeline: strict lint, compact LOD, light/dark export, and ${rendered.renderer} PNG render passed`);
} finally {
  fs.rmSync(tmpOutDir, { recursive: true, force: true });
}

// 4. Verify faulty-figure/ fails direct Model-First purity audit while cli/check.mjs skips evals/ on repo scan
const figAudit = auditFigureDir(path.join(ROOT, 'evals', 'attachments', 'faulty-figure'), { runChecks: true });
assert.equal(figAudit.ok, false, 'faulty-figure must fail direct auditFigureDir');
assert.ok(figAudit.errors.some(e => /three/i.test(e)), `Expected faulty-figure to flag Three.js import, got: ${figAudit.errors.join('; ')}`);
console.log('PASS  evals/faulty-figure: purity gate caught forbidden Three.js import cleanly');

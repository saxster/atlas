  '/* Non-boosting mark isolation: fades unrelated strokes/text while preserving selected marks verbatim */',
  '.draft-frame { display: flex; flex-direction: column; border: 1px solid var(--faint, #d4d4d6); border-radius: 12px; background: var(--card, #fbfbfa); overflow: hidden; }',

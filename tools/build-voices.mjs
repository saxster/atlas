// node tools/build-voices.mjs [--check]
// Single-source generator from engine/voices.json -> engine/voices.js and generated table in docs/voices/catalog.md.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');
const SRC_PATH = path.join(ROOT, 'engine', 'voices.json');
const OUT_JS = path.join(ROOT, 'engine', 'voices.js');
const CATALOG_MD = path.join(ROOT, 'docs', 'voices', 'catalog.md');

const VALID_QUIRKS = new Set(['bland', 'atelier', 'slightly-quirky', 'playful', 'wild']);
const VALID_MEDIUMS = new Set(['paper-ink', 'ciechanow', 'pencil-wash', 'moebius', 'risograph']);
const VALID_FEELS = new Set(['smooth', 'spring', 'instant']);
const VALID_TYPES = new Set(['editorial', 'clean', 'technical']);
const VALID_RADII = new Set(['sharp', 'soft', 'round']);

const manifest = JSON.parse(fs.readFileSync(SRC_PATH, 'utf8'));
const voicesList = Array.isArray(manifest.voices) ? manifest.voices : [];
if (!voicesList.length) throw new Error('engine/voices.json: missing voices array');

const voicesById = {};
const seenIds = new Set();
for (const v of voicesList) {
  if (!v.id || seenIds.has(v.id)) throw new Error(`engine/voices.json: duplicate or empty id "${v.id}"`);
  seenIds.add(v.id);
  if (!VALID_QUIRKS.has(v.quirk)) throw new Error(`engine/voices.json [${v.id}]: invalid quirk "${v.quirk}"`);
  if (!VALID_MEDIUMS.has(v.medium)) throw new Error(`engine/voices.json [${v.id}]: invalid medium "${v.medium}"`);
  if (!VALID_FEELS.has(v.feel)) throw new Error(`engine/voices.json [${v.id}]: invalid feel "${v.feel}"`);
  if (!VALID_TYPES.has(v.typography)) throw new Error(`engine/voices.json [${v.id}]: invalid typography "${v.typography}"`);
  if (!VALID_RADII.has(v.radius)) throw new Error(`engine/voices.json [${v.id}]: invalid radius "${v.radius}"`);
  if (!fs.existsSync(path.join(ROOT, v.doc))) throw new Error(`engine/voices.json [${v.id}]: missing doc "${v.doc}"`);
  voicesById[v.id] = v;
}

const defaultVoice = manifest.defaultVoice || 'bugged-sketchbook';
if (!voicesById[defaultVoice]) throw new Error(`engine/voices.json: defaultVoice "${defaultVoice}" not found`);

const aliases = manifest.aliases || {};
for (const [alias, target] of Object.entries(aliases)) {
  if (!voicesById[target]) throw new Error(`engine/voices.json: alias "${alias}" points to unknown voice "${target}"`);
}

const voiceIds = voicesList.map(v => v.id);

const generatedJs = [
  '// Generated by tools/build-voices.mjs from engine/voices.json — do not edit by hand.',
  '// Zero DOM globals, zero Node built-ins, zero Three.js imports.',
  'function deepFreeze(value) {',
  '  if (value && typeof value === "object") {',
  '    for (const child of Object.values(value)) deepFreeze(child);',
  '    Object.freeze(value);',
  '  }',
  '  return value;',
  '}',
  '',
  `export const DEFAULT_VOICE = ${JSON.stringify(defaultVoice)};`,
  '',
  `export const VOICE_IDS = Object.freeze(${JSON.stringify(voiceIds)});`,
  '',
  `export const VOICE_ALIASES = Object.freeze(${JSON.stringify(aliases, null, 2)});`,
  '',
  `export const VOICES = deepFreeze(${JSON.stringify(voicesById, null, 2)});`,
  '',
  'export function resolveVoice(input = DEFAULT_VOICE) {',
  '  if (input && typeof input === "object" && input.id && VOICES[input.id]) {',
  '    return { ...VOICES[input.id] };',
  '  }',
  '  const raw = String(input || DEFAULT_VOICE).trim().toLowerCase();',
  '  const canonical = VOICES[raw] ? raw : (VOICE_ALIASES[raw] || DEFAULT_VOICE);',
  '  return { ...VOICES[canonical] };',
  '}',
  '',
  'export function listVoices() {',
  '  return VOICE_IDS.map(id => VOICES[id]);',
  '}',
  '',
].join('\n');

const matrixBlock = [
  '<!-- BEGIN GENERATED: voice-matrix -->',
  '| Voice | Reg | Quirk | Medium | Feel | Type | Corners | Accent | Paper / Card |',
  '| --- | :---: | --- | --- | --- | --- | --- | --- | --- |',
  ...voicesList.map(v => (
    `| \`${v.id}\` | R${v.register} | \`${v.quirk}\` | \`${v.medium}\` | \`${v.feel}\` | \`${v.typography}\` | \`${v.radius}\` | \`${v.accent}\` | \`${v.paper}\` / \`${v.card}\` |`
  )),
  '<!-- END GENERATED: voice-matrix -->',
].join('\n');

let stale = 0;
function syncFile(filePath, nextContent) {
  const cur = fs.existsSync(filePath) ? fs.readFileSync(filePath, 'utf8') : '';
  if (cur === nextContent) return;
  if (CHECK) {
    console.error(`STALE ${path.relative(ROOT, filePath)} (run node tools/build-voices.mjs)`);
    stale++;
  } else {
    fs.writeFileSync(filePath, nextContent, 'utf8');
    console.log(`wrote ${path.relative(ROOT, filePath)}`);
  }
}

syncFile(OUT_JS, generatedJs);

if (fs.existsSync(CATALOG_MD)) {
  const src = fs.readFileSync(CATALOG_MD, 'utf8');
  const begin = '<!-- BEGIN GENERATED: voice-matrix -->';
  const end = '<!-- END GENERATED: voice-matrix -->';
  const bi = src.indexOf(begin);
  const ei = src.indexOf(end, bi + begin.length);
  if (bi >= 0 && ei >= 0) {
    const next = src.slice(0, bi) + matrixBlock + src.slice(ei + end.length);
    syncFile(CATALOG_MD, next);
  }
}

if (stale > 0) process.exit(1);
if (CHECK) console.log('voice manifest codegen: current');
